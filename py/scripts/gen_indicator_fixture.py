"""Regenerate testdata/indicators.json, the shared fixture for the Python and TS indicators.

Run from py/: uv run python scripts/gen_indicator_fixture.py
The input is a fixed pseudo-random walk (with flat stretches to hit the H9 == L9 and
zero-change edge cases); expected values come from stockhub.engine.indicators.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from stockhub.engine import indicators as ind

OUT = Path(__file__).resolve().parents[2] / "testdata" / "indicators.json"


def series(length: int = 120) -> tuple[list[float], list[float], list[float]]:
    rng = random.Random(20261018)  # noqa: S311 - fixture data, not crypto
    closes, highs, lows = [], [], []
    price = 100.0
    for i in range(length):
        flat = 40 <= i < 52  # a flat stretch: zero changes and H9 == L9
        change = 0.0 if flat else round(rng.uniform(-3, 3), 2)
        price = round(max(1.0, price + change), 2)
        spread = 0.0 if flat else round(rng.uniform(0, 2), 2)
        closes.append(price)
        highs.append(round(price + spread, 2))
        lows.append(round(price - spread, 2))
    return highs, lows, closes


def main() -> None:
    highs, lows, closes = series()
    macd = ind.macd(closes)
    kd = ind.kd(highs, lows, closes)
    data = {
        "comment": "Generated by py/scripts/gen_indicator_fixture.py; do not edit by hand.",
        "input": {"high": highs, "low": lows, "close": closes},
        "expected": {
            "sma5": ind.sma(closes, 5),
            "sma20": ind.sma(closes, 20),
            "sma60": ind.sma(closes, 60),
            "ema12": ind.ema(closes, 12),
            "macd_dif": macd.dif,
            "macd_signal": macd.signal,
            "macd_histogram": macd.histogram,
            "kd_k": kd.k,
            "kd_d": kd.d,
            "rsi14": ind.rsi(closes),
        },
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
