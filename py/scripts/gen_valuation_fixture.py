"""Regenerate testdata/valuation.json, the shared fixture for the Python and TS valuation.

Run from py/: uv run python scripts/gen_valuation_fixture.py
Input: three years of weekday closes (a fixed pseudo-random walk), quarters with a loss
stretch and a late filer, dividends (one exactly 365 days before a price day); expected
values come from stockhub.engine.valuation.
"""

from __future__ import annotations

import json
import random
from dataclasses import asdict
from datetime import date, timedelta
from pathlib import Path

from stockhub.engine import valuation as v

OUT = Path(__file__).resolve().parents[2] / "testdata" / "valuation.json"


def inputs() -> tuple[list[v.PricePoint], list[v.QuarterPoint], list[v.Dividend]]:
    rng = random.Random(20261020)  # noqa: S311 - fixture data, not crypto
    prices = []
    day, price = date(2023, 1, 2), 50.0
    while day <= date(2026, 3, 31):
        if day.isoweekday() < 6:
            price = round(max(5.0, price + rng.uniform(-1.5, 1.5)), 2)
            prices.append(v.PricePoint(day.isoformat(), price))
        day += timedelta(days=1)
    quarters = []
    eps = [1.2, 1.5, -0.4, -1.1, -0.3, 0.8, 2.0, 2.4, 2.6, 2.9, 3.1, 3.4, 3.6]
    for i, value in enumerate(eps):
        year, q = 2023 + (i + 2) // 4 - 1, (i + 2) % 4
        period_end = date(year, 3 * (q + 1), 31 if q in (0, 3) else 30)
        deadline = {0: (5, 15), 1: (8, 14), 2: (11, 14), 3: (3, 31)}[q]
        available = date(year + (1 if q == 3 else 0), *deadline)
        if i == 5:
            available += timedelta(days=20)  # a late filer
        quarters.append(
            v.QuarterPoint(
                period_end.isoformat(),
                available.isoformat(),
                value,
                None if i == 4 else round(20 + i * 0.7, 2),  # one quarter without book value
            )
        )
    dividends = [
        v.Dividend("2023-07-12", 1.5),
        v.Dividend("2024-02-29", 0.5),  # leap day
        v.Dividend("2024-07-11", 1.8),
        v.Dividend("2025-07-10", 2.0),
    ]
    return prices, quarters, dividends


def main() -> None:
    prices, quarters, dividends = inputs()
    series = v.valuation_series(prices, quarters, dividends)
    summaries = {
        f"{metric}_{years}y": asdict(v.summarize(series, metric, years))
        for metric in ("pe", "pb", "dividend_yield")
        for years in (1, 2)
    }
    pe_multiples = v.band_multiples(v.metric_values(v.window(series, 2), "pe"))
    pb_multiples = v.band_multiples(v.metric_values(v.window(series, 2), "pb"))
    data = {
        "comment": "Generated by py/scripts/gen_valuation_fixture.py; do not edit by hand.",
        "input": {
            "prices": [asdict(p) for p in prices],
            "quarters": [asdict(q) for q in quarters],
            "dividends": [asdict(d) for d in dividends],
        },
        "expected": {
            "series": [asdict(p) for p in series],
            "summaries": summaries,
            "pe_multiples": pe_multiples,
            "pb_multiples": pb_multiples,
            "pe_bands_tail": v.river_bands(series[-5:], "pe", pe_multiples),
            "shift_years": {d: v.shift_years(d, -2) for d in ("2024-02-29", "2026-03-31")},
        },
    }
    OUT.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
